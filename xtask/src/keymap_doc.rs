//! `cargo xtask keymap-doc [--check]`: generate `docs/KEYBOARD.md` and the
//! printable cheat-sheet source `docs/user/shortcuts-cheatsheet.md` from the
//! `cl-model` command table (Q-161). `--check` fails when either file is stale.

use anyhow::{Result, bail};
use cl_model::keymap::{BANK_FEED_KEYS, DATE_KEYS, FIXED_KEYS, Scope};
use cl_model::{COMMANDS, Command, Menu};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const HEADER: &str = "<!-- Generated by `cargo xtask keymap-doc` from crates/cl-model/src/commands.rs. Do not edit by hand. -->\n";

fn row(c: &Command) -> String {
    let key = c
        .shortcut
        .map_or_else(|| "-".to_string(), |s| format!("`{s}`"));
    format!("| {key} | {} | `{}` |\n", c.label, c.id)
}

fn pairs(out: &mut String, title: &str, rows: &[(&str, &str)]) {
    let _ = writeln!(out, "## {title}\n\n| Keys | Action |\n| --- | --- |");
    for (k, a) in rows {
        let _ = writeln!(out, "| `{k}` | {a} |");
    }
    out.push('\n');
}

/// The full reference.
#[must_use]
pub fn keyboard_md() -> String {
    let mut out = String::from(HEADER);
    out.push_str(
        "\n# Keyboard shortcuts\n\n\
         Every action is reachable from the keyboard. Press `Ctrl+K` to search for any \
         command, or `Ctrl+/` to see the shortcuts for the screen you are on. On macOS, \
         `Ctrl` means `Cmd` and `Alt` means `Option`.\n\n\
         When two scopes use the same keys, the innermost one wins: a form beats a window, \
         and a window beats the whole app.\n\n",
    );
    for scope in [Scope::Global, Scope::Window, Scope::Form] {
        let bound: Vec<&Command> = COMMANDS
            .iter()
            .filter(|c| c.scope == scope && c.shortcut.is_some())
            .collect();
        if bound.is_empty() {
            continue;
        }
        let _ = writeln!(
            out,
            "## {}\n\n| Keys | Command | Id |\n| --- | --- | --- |",
            scope.title()
        );
        for c in bound {
            out.push_str(&row(c));
        }
        out.push('\n');
    }
    pairs(&mut out, "Always the same in forms and grids", FIXED_KEYS);
    pairs(&mut out, "Date fields", DATE_KEYS);
    pairs(&mut out, "Bank Feed", BANK_FEED_KEYS);
    out.push_str(
        "## Commands without a shortcut\n\nFind these from the menus or with `Ctrl+K`.\n\n",
    );
    for m in Menu::ALL {
        let names: Vec<String> = COMMANDS
            .iter()
            .filter(|c| c.menu == Some(*m) && c.shortcut.is_none())
            .map(|c| c.label.to_string())
            .collect();
        if !names.is_empty() {
            let _ = writeln!(out, "- **{}:** {}", m.title(), names.join(", "));
        }
    }
    out
}

/// The one-page cheat sheet (source for the printable PDF built in P38).
#[must_use]
pub fn cheatsheet_md() -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n# ClientLedger shortcuts (one page)\n\n");
    for m in Menu::ALL {
        let bound: Vec<&Command> = COMMANDS
            .iter()
            .filter(|c| c.menu == Some(*m) && c.shortcut.is_some())
            .collect();
        if bound.is_empty() {
            continue;
        }
        let _ = writeln!(out, "**{}**\n", m.title());
        for c in bound {
            if let Some(s) = c.shortcut {
                let _ = writeln!(out, "- `{s}` {}", c.label);
            }
        }
        out.push('\n');
    }
    let forms: Vec<&Command> = COMMANDS
        .iter()
        .filter(|c| c.menu.is_none() && c.shortcut.is_some())
        .collect();
    out.push_str("**Forms and grids**\n\n");
    for c in forms {
        if let Some(s) = c.shortcut {
            let _ = writeln!(out, "- `{s}` {}", c.label);
        }
    }
    out.push_str("\n**Dates**: ");
    out.push_str(
        &DATE_KEYS
            .iter()
            .map(|(k, a)| format!("`{k}` {a}"))
            .collect::<Vec<_>>()
            .join("; "),
    );
    out.push('\n');
    out
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

/// Entry point.
pub fn keymap_doc(args: &[String]) -> Result<()> {
    let check = args.iter().any(|a| a == "--check");
    let files = [
        (root().join("docs/KEYBOARD.md"), keyboard_md()),
        (
            root().join("docs/user/shortcuts-cheatsheet.md"),
            cheatsheet_md(),
        ),
    ];
    let mut stale = Vec::new();
    for (path, text) in &files {
        let current = std::fs::read_to_string(path).unwrap_or_default();
        // Git may check files out with CRLF on Windows.
        if current.replace("\r\n", "\n") == *text {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(path, text)?;
            println!("keymap-doc: wrote {}", path.display());
        }
    }
    if !stale.is_empty() {
        bail!(
            "keymap-doc: out of date: {} (run `cargo xtask keymap-doc`)",
            stale.join(", ")
        );
    }
    if check {
        println!("keymap-doc: generated docs are current");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_bound_shortcut_appears_in_the_reference() {
        let md = keyboard_md();
        for c in COMMANDS.iter().filter(|c| c.shortcut.is_some()) {
            assert!(md.contains(&format!("`{}`", c.id)), "{}", c.id);
        }
        assert!(md.contains("`Ctrl+Shift+R`"));
        assert!(md.contains("Date fields"));
    }

    #[test]
    fn cheatsheet_is_short() {
        assert!(cheatsheet_md().lines().count() < 120);
    }
}
