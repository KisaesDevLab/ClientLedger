//! Typed record ids over UUIDs.
//!
//! Each kind is its own type, so an account id can never be passed where a
//! contact id is expected. Parsing is strict: exactly the 36-character
//! hyphenated form (any letter case). Output is always lowercase. There are no
//! conversions between kinds; ids are created by the engine (or, for request
//! ids, by the caller with its own random source) and wrapped with
//! `from_uuid`.

use serde::{Deserialize, Deserializer, Serialize, Serializer};
use std::fmt;
use std::str::FromStr;
use uuid::Uuid;

/// Why a string is not a valid id.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum IdError {
    /// Not 36 characters with hyphens at positions 8, 13, 18 and 23.
    #[error("id is not a 36-character hyphenated UUID")]
    Format,
    /// The right shape, but a character is not a hex digit.
    #[error("id contains a character that is not a hex digit")]
    Digit,
}

/// Parse the strict hyphenated form.
///
/// # Errors
/// [`IdError::Format`] for any other shape (braces, `urn:uuid:`, 32-digit
/// simple form, whitespace); [`IdError::Digit`] for a non-hex character.
pub fn parse_uuid(s: &str) -> Result<Uuid, IdError> {
    let b = s.as_bytes();
    if b.len() != 36 {
        return Err(IdError::Format);
    }
    for (i, c) in b.iter().enumerate() {
        let hyphen = matches!(i, 8 | 13 | 18 | 23);
        if hyphen != (*c == b'-') {
            return Err(IdError::Format);
        }
        if !hyphen && !c.is_ascii_hexdigit() {
            return Err(IdError::Digit);
        }
    }
    Uuid::try_parse(s).map_err(|_| IdError::Digit)
}

macro_rules! typed_id {
    ($($(#[$doc:meta])* $name:ident),+ $(,)?) => {$(
        $(#[$doc])*
        #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub struct $name(Uuid);

        impl $name {
            /// Wrap a UUID received from the engine or generated by the caller.
            #[must_use]
            pub const fn from_uuid(id: Uuid) -> Self {
                Self(id)
            }

            /// The underlying UUID.
            #[must_use]
            pub const fn as_uuid(&self) -> &Uuid {
                &self.0
            }

            /// Strict parse (see [`parse_uuid`]).
            ///
            /// # Errors
            /// See [`IdError`].
            pub fn parse(s: &str) -> Result<Self, IdError> {
                parse_uuid(s).map(Self)
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(&self.0.hyphenated(), f)
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, "{}({})", stringify!($name), self.0.hyphenated())
            }
        }

        impl FromStr for $name {
            type Err = IdError;
            fn from_str(s: &str) -> Result<Self, IdError> {
                Self::parse(s)
            }
        }

        impl Serialize for $name {
            fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
                s.collect_str(&self.0.hyphenated())
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
                d.deserialize_str(IdVisitor(stringify!($name))).map(Self)
            }
        }
    )+};
}

struct IdVisitor(&'static str);

impl serde::de::Visitor<'_> for IdVisitor {
    type Value = Uuid;

    fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "a hyphenated UUID string ({})", self.0)
    }

    fn visit_str<E: serde::de::Error>(self, v: &str) -> Result<Uuid, E> {
        parse_uuid(v).map_err(E::custom)
    }
}

typed_id!(
    /// An engine tenant (a company or the hidden owner workspace).
    TenantId,
    /// The engine `companies` row inside a tenant.
    CompanyId,
    /// A user.
    UserId,
    /// A chart-of-accounts account.
    AccountId,
    /// A customer, vendor or other name.
    ContactId,
    /// A product or service item.
    ItemId,
    /// A tag.
    TagId,
    /// A tag group.
    TagGroupId,
    /// A transaction header.
    TransactionId,
    /// One line of a transaction.
    JournalLineId,
    /// The `X-Request-Id` of one logical request.
    RequestId,
    /// A daily-sales layout (the engine's daily-sales template, P14).
    DailyTemplateId,
    /// One line of a daily-sales layout.
    DailyLineId,
    /// One business day of daily sales (the engine's daily-sales entry).
    DailyEntryId,
);

#[cfg(test)]
mod tests {
    use super::*;

    const ID: &str = "7f3a2c10-5b6d-4e8f-9a0b-1c2d3e4f5a6b";

    #[test]
    fn parses_hyphenated_any_case_and_prints_lowercase() {
        let a = AccountId::parse(ID).unwrap();
        let b = AccountId::parse(&ID.to_uppercase()).unwrap();
        assert_eq!(a, b);
        assert_eq!(b.to_string(), ID);
        assert_eq!(format!("{b:?}"), format!("AccountId({ID})"));
        assert_eq!(ID.parse::<AccountId>().unwrap(), a);
        assert_eq!(AccountId::from_uuid(*a.as_uuid()), a);
    }

    #[test]
    fn rejects_other_forms() {
        let simple = ID.replace('-', "");
        let cases = [
            "",
            simple.as_str(),
            "{7f3a2c10-5b6d-4e8f-9a0b-1c2d3e4f5a6b}",
            "urn:uuid:7f3a2c10-5b6d-4e8f-9a0b-1c2d3e4f5a6b",
            "7f3a2c10-5b6d-4e8f-9a0b-1c2d3e4f5a6b ",
            "7f3a2c105-b6d-4e8f-9a0b-1c2d3e4f5a6b",
        ];
        for c in cases {
            assert_eq!(ContactId::parse(c), Err(IdError::Format), "{c:?}");
        }
        // Right length but a space inside: still refused.
        assert!(ContactId::parse(" 7f3a2c10-5b6d-4e8f-9a0b-1c2d3e4f5a6").is_err());
        assert_eq!(
            ContactId::parse("7f3a2c10-5b6d-4e8f-9a0b-1c2d3e4f5a6g"),
            Err(IdError::Digit)
        );
    }

    #[test]
    fn serde_uses_strings_only() {
        let id = TransactionId::parse(ID).unwrap();
        let json = serde_json::to_string(&id).unwrap();
        assert_eq!(json, format!("\"{ID}\""));
        let back: TransactionId = serde_json::from_str(&json).unwrap();
        assert_eq!(back, id);
        assert!(serde_json::from_str::<TransactionId>("12").is_err());
        assert!(serde_json::from_str::<TransactionId>("\"{x}\"").is_err());
        let upper: TransactionId =
            serde_json::from_str(&format!("\"{}\"", ID.to_uppercase())).unwrap();
        assert_eq!(upper, id);
    }

    #[test]
    fn kinds_are_distinct_types_with_ordering() {
        let a = TagId::parse("00000000-0000-0000-0000-000000000001").unwrap();
        let b = TagId::parse("00000000-0000-0000-0000-000000000002").unwrap();
        assert!(a < b);
        // Same UUID, different kind: only an explicit from_uuid crosses over.
        let g = TagGroupId::from_uuid(*a.as_uuid());
        assert_eq!(g.as_uuid(), a.as_uuid());
    }
}
